/**
 * Generates CSS utilities for `{prop}-[var(--x)]/NN` classes that Tailwind
 * silently drops (Tailwind cannot apply an opacity modifier to a `var()`
 * arbitrary value — no class is emitted at all). We emit the equivalent
 * `color-mix(in srgb, var(--x) NN%, transparent)` rules so every translucent
 * surface/border/text in the app actually renders.
 *
 * Usage: node scripts/gen-var-opacity-utils.mjs   (prints CSS to stdout)
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const SRC = decodeURIComponent(new URL('../src/', import.meta.url).pathname).replace(/^\/([A-Za-z]:)/, '$1');

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      out.push(...walk(full));
    } else if (/\.(tsx|ts)$/.test(entry)) {
      out.push(full);
    }
  }
  return out;
}

const PROPERTY = {
  bg: 'background-color',
  border: 'border-color',
  text: 'color',
  ring: '--tw-ring-color',
  divide: 'border-color',
  from: '--tw-gradient-from',
  via: '--tw-gradient-via',
  to: '--tw-gradient-to',
};

const found = new Set();
for (const file of walk(SRC)) {
  const src = readFileSync(file, 'utf8');
  const re = /\b(bg|border|text|ring|divide|from|via|to)-\[var\((--[a-zA-Z0-9-]+)\)\]\/(\d+)\b/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    found.add(`${m[1]}\u0000${m[2]}\u0000${m[3]}`);
  }
}

const escapeClass = (s) =>
  s.replace(/\\/g, '\\\\').replace(/([\[\]\(\)\/:\.#])/g, '\\$1');

const rules = [...found]
  .sort()
  .map((combo) => {
    const [prefix, variable, opacity] = combo.split('\u0000');
    const cls = `${prefix}-[var(${variable})]/${opacity}`;
    const prop = PROPERTY[prefix];
    const value = `color-mix(in srgb, ${variable} ${opacity}%, transparent)`;
    return `.${escapeClass(cls)}{${prop}:${value}}`;
  });

console.log(`/* Auto-generated by scripts/gen-var-opacity-utils.mjs — ${rules.length} utilities.
   Tailwind cannot emit opacity modifiers on var() arbitrary values, so these
   color-mix() fallbacks restore the intended translucent surfaces/borders. */`);
console.log(rules.join('\n'));
